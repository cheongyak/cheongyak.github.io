"""2026-11-21 고창 데시앙(2026000596~598) 계약금 비율 점검 거짓 경보: '(단위: 원)' 옵션 표 줄
'엔지니어드 스톤 870,000 87,000 783,000'을 천원 집값 줄로 키워 10% 로 57~75줄 세어, 원문 표 머리·집값 줄이 5% 인데 '표 줄과 안 맞음'.
표 위 단위가 '원' 이면 키우지 않는다. 준공 뒤 무순위 '(단위: 천원)' 집값 줄 '805,000 80,500 724,500'(10%+90%)은 그대로 센다."""
from tools.qa.pay_audit import row_rates

HOUSE5 = "■ 공급금액 (단위: 천원)\n84A 1층 517,200 25,860 310,320 181,020\n84A 2층 520,000 26,000 312,000 182,000\n"
OPTION = "■ 추가선택품목 (단위: 원, VAT 포함)\n현 관 바 닥 엔지니어드 스톤 870,000 87,000 783,000\n주방 상판 1,200,000 120,000 1,080,000\n"


def test_won_option_rows_not_scaled():
    r = row_rates(HOUSE5 + OPTION)
    assert r.get(5) == 2 and not r.get(10), r


def test_thousand_won_house_rows_10_90_still_counted():
    r = row_rates("공급금액 계약금 (10%) 잔금 (90%) (단위: ㎡, 천원)\n10층 1 322,000 483,000 805,000 80,500 724,500\n11층 2 324,000 486,000 810,000 81,000 729,000\n")
    assert r.get(10, 0) >= 2, r


def test_option_rows_without_unit_header_still_scaled_as_before():
    # 단위 표기가 없으면 예전처럼 천원·만원을 시도 (예전 동작 유지)
    assert row_rates("엔지니어드 스톤 870,000 87,000 783,000\n").get(10) == 1
